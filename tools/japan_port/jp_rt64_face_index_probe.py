#!/usr/bin/env python3
"""Fail-closed v6 RT64 robot workload face-index probe for original JP gameplay.

Upgrades *only* the exact already-installed v5 interpreter generated by the
pinned v4 + v5 tools. The C++ instrumentation is env-gated and read-only; it
never edits ROM, game RAM or rendering behaviour. Do not merge into production.

Place the published jp_rt64_robot_probe.py and jp_rt64_triangle_gate_probe.py
next to this script so their canonical source transformations can be verified.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import jp_rt64_robot_probe as v4
import jp_rt64_triangle_gate_probe as v5

MARKER = 'GOEMON_JP_RT64_FACE_INDEX_V6'
RELATIVE = v4.RELATIVE
BACKUP_SUFFIX = '.pre-jp-face-index-v6'

FIELD_ANCHOR = '            uint32_t gate_skip = 0; // Calls that hit the both-faces-culling early return.\n'
FIELD_REPLACE = FIELD_ANCHOR + '''            uint32_t face_index_triangles = 0; // RSP faceIndices growth / 3, independent of drawCall flushes.
            uint32_t face_index_ambiguous = 0; // Cursor changed, vector shrank, or inconsistent command growth.
'''

PRE_ANCHOR = '''                const uint32_t goemon_probe_tri_before = goemon_probe_index >= 0 ? state->drawCall.triangleCount : 0u;
'''
PRE_REPLACE = PRE_ANCHOR + '''                // GOEMON_JP_RT64_FACE_INDEX_V6: for G_TRI1/G_TRI2 only, sample the
                // *workload's* monotonically appended face index vector. drawCall's
                // triangleCount is reset by State::flush() within the handler.
                const bool goemon_probe_is_tri = goemon_probe_index >= 0 && (opCode == 0xB1 || opCode == 0xBF);
                const int goemon_probe_cursor_before = goemon_probe_is_tri && state->ext.workloadQueue
                    ? state->ext.workloadQueue->writeCursor : -1;
                const bool goemon_probe_cursor_valid = goemon_probe_cursor_before >= 0 &&
                    goemon_probe_cursor_before < WORKLOAD_QUEUE_SIZE;
                const size_t goemon_probe_faces_before = goemon_probe_cursor_valid
                    ? state->ext.workloadQueue->workloads[goemon_probe_cursor_before].drawData.faceIndices.size()
                    : 0u;
'''

AFTER_ANCHOR = '''                if (goemon_probe_index >= 0) {
                    goemon_jp_rt64_probe_after(state, goemon_probe_index, opCode, goemon_probe_arg, goemon_probe_tri_before);
                }
'''
AFTER_REPLACE = '''                if (goemon_probe_is_tri) {
                    auto &goemon_face_record = goemonProbeLists[goemon_probe_index];
                    // GOEMON_JP_RT64_FACE_INDEX_V6: no writes or changes to handlers.
                    // For a F3DEX TRI2 command there are two drawIndexedTri calls,
                    // each appending exactly three indices after the early gate.
                    const int goemon_probe_cursor_after = state->ext.workloadQueue
                        ? state->ext.workloadQueue->writeCursor : -1;
                    const unsigned goemon_probe_max_faces = opCode == 0xB1 ? 6u : 3u;
                    if (goemon_probe_cursor_valid &&
                        goemon_probe_cursor_after == goemon_probe_cursor_before) {
                        const size_t goemon_probe_faces_after =
                            state->ext.workloadQueue->workloads[goemon_probe_cursor_after]
                                .drawData.faceIndices.size();
                        if (goemon_probe_faces_after >= goemon_probe_faces_before &&
                            goemon_probe_faces_after - goemon_probe_faces_before <= goemon_probe_max_faces &&
                            (goemon_probe_faces_after - goemon_probe_faces_before) % 3u == 0u) {
                            goemon_face_record.face_index_triangles += uint32_t(
                                (goemon_probe_faces_after - goemon_probe_faces_before) / 3u);
                        }
                        else goemon_face_record.face_index_ambiguous++;
                    }
                    else goemon_face_record.face_index_ambiguous++;
                }
                if (goemon_probe_index >= 0) {
                    goemon_jp_rt64_probe_after(state, goemon_probe_index, opCode, goemon_probe_arg, goemon_probe_tri_before);
                }
'''

END_FMT_ANCHOR = '                                     "vertices=%u matrices=%u gate_pass=%u gate_skip=%u\\n",\n'
END_FMT_REPLACE = '                                     "vertices=%u matrices=%u gate_pass=%u gate_skip=%u "\n' + \
                  '                                     "face_index_tri=%u face_ambiguous=%u\\n",\n'
END_ARGS_ANCHOR = '                             record.gate_pass, record.gate_skip);\n'
END_ARGS_REPLACE = '                             record.gate_pass, record.gate_skip,\n' + \
                   '                             record.face_index_triangles, record.face_index_ambiguous);\n'


def replace_exact_once(text: str, anchor: str, replacement: str, name: str) -> str:
    count = text.count(anchor)
    if count != 1:
        raise ValueError(f'expected exactly one {name} anchor, found {count}')
    return text.replace(anchor, replacement, 1)


def transform(v5_source: str) -> str:
    if MARKER in v5_source:
        raise ValueError('v6 face-index probe is already installed')
    if v5.V5_MARKER not in v5_source:
        raise ValueError('v5 triangle-cull-gate probe is absent')
    result = v5_source
    for name,old,new in (
        ('v5 record',FIELD_ANCHOR,FIELD_REPLACE),
        ('v5 pre-dispatch site',PRE_ANCHOR,PRE_REPLACE),
        ('v5 post-dispatch site',AFTER_ANCHOR,AFTER_REPLACE),
        ('v5 END format',END_FMT_ANCHOR,END_FMT_REPLACE),
        ('v5 END arguments',END_ARGS_ANCHOR,END_ARGS_REPLACE),
    ):
        result = replace_exact_once(result,old,new,name)
    assert result != v5_source
    return result


def plan(rt64_dir: Path, rom: Path) -> tuple[Path, bytes, bytes]:
    v4.validate_rom(rom)
    target = rt64_dir / RELATIVE
    pinned_backup = target.with_name(target.name + '.pre-jp-robot-probe')
    v5_backup = target.with_name(target.name + '.pre-jp-tri-gate-v5')
    v6_backup = target.with_name(target.name + BACKUP_SUFFIX)
    pristine = pinned_backup.read_bytes()
    if v4.blob_hash(pristine) != v4.ORIGINAL_BLOB_SHA1:
        raise ValueError('pinned original RT64 interpreter backup does not match Git blob')
    expected_v4 = v4.transform(pristine.decode('utf-8'))
    expected_v5 = v5.transform(expected_v4).encode('utf-8')
    if v5_backup.read_bytes() != expected_v4.encode('utf-8'):
        raise ValueError('v5 backup does not match exact source-only v4 transform')
    current = target.read_bytes()
    if current != expected_v5:
        raise ValueError('installed v5 interpreter differs from exact source transform; no changes made')
    if v6_backup.exists():
        raise ValueError('v6 backup already exists; refuse repeated instrumentation')
    changed = transform(expected_v5.decode('utf-8')).encode('utf-8')
    return target, current, changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rt64-dir',type=Path,default=Path('lib/rt64'))
    parser.add_argument('--rom',type=Path,required=True)
    group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--dry-run',action='store_true')
    group.add_argument('--confirm-modify-private-rt64',action='store_true')
    args=parser.parse_args()
    try:
        target,current,changed=plan(args.rt64_dir,args.rom)
        backup=target.with_name(target.name+BACKUP_SUFFIX)
        if args.confirm_modify_private_rt64:
            backup.write_bytes(current)
            try:
                target.write_bytes(changed)
            except BaseException:
                target.write_bytes(current)
                raise
        print('exact pinned RT64 original + v4 + v5 source transformations: PASS')
        print('original Japanese decompressed ROM SHA-1: PASS')
        print('mode: '+('v6 workload face-index probe installed (rebuild required)' if args.confirm_modify_private_rt64 else 'validated only'))
        print('source: '+str(target))
        print('backup: '+str(backup))
    except (OSError, ValueError, UnicodeError) as error:
        parser.error(str(error))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())